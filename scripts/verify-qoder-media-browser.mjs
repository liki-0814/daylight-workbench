// Desktop 1440 check of the Qoder 图像与视频 list with isolated data and a stub upstream (no network, no credits).
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, rm, writeFile, readFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { createWorkbench } from '../server.mjs';
const { chromium } = await import(process.env.DAYLIGHT_PLAYWRIGHT_MODULE || 'playwright');
const directory = await mkdtemp(path.join(os.tmpdir(), 'daylight-qoder-media-ui-'));
const output = path.resolve(process.argv[2] || '.local/verification/qoder-media');
await mkdir(output, { recursive: true });
await mkdir(path.join(directory, 'qoder'), { recursive: true });
await writeFile(path.join(directory, 'qoder', 'account.json'), JSON.stringify({ id: 'acc_ui', profile: 'qoder', credential: { uid: 'ui', access: 'x', refresh: 'x', machineId: 'm', machineToken: 'm', expires: Date.now() + 3_600_000 } }));
const upstream = [];
const fetchImpl = async url => { upstream.push(String(url)); return Response.json({ error: 'offline stub' }, { status: 503 }); };
const server = await createWorkbench({ dataDir: directory, proxyOptions: { fetchImpl, includeGateway: false, includeAgy: false, includeGrok: false, piOptions: { piDir: path.join(directory, 'pi') } }, extensionsOptions: { agentsRoot: path.join(directory, 'agents') } });
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
const browser = await chromium.launch({ headless: true, executablePath: process.env.DAYLIGHT_CHROME_EXECUTABLE });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [], checks = [];
page.on('pageerror', error => errors.push(error.message));
const panel = page.locator('#proxy-panel-qoder'), section = panel.locator('#qoder-media-models'), toggle = id => panel.getByRole('checkbox', { name: '启用 ' + id, exact: true });
try {
  await page.goto(`http://127.0.0.1:${server.address().port}/#proxy`);
  await page.getByRole('tab', { name: 'Qoder', exact: true }).click();
  await section.waitFor();
  const summary = section.locator('summary').first();
  if (await section.evaluate(element => element.open === false)) await summary.click();
  await toggle('qwen-image-3.0').waitFor();
  const rows = await section.locator('.ui-media-model').allInnerTexts();
  assert.equal(rows.length, 2);
  assert.match(rows[0], /Qwen-Image 3\.0 \(映射待确认\)/); assert.match(rows[0], /图像 · 已登录可用 · .*ge3i/);
  assert.match(rows[1], /万相 3\.0/); assert.match(rows[1], /wan3\.0-video/); assert.match(rows[1], /视频 · 已登录可用 · .*wan30/);
  checks.push('desktop 1440: two real-name rows with hint, id and upstream note');
  assert.equal(await toggle('wan3.0-video').isChecked(), true);
  await toggle('wan3.0-video').uncheck();
  await section.getByText('已保存', { exact: true }).waitFor();
  assert.equal(await panel.locator('.proxy-disabled-models').count(), 0);
  assert.equal(await section.locator('.proxy-model-heading.is-pending').count(), 1);
  assert.equal(await section.locator('.proxy-model:has(.is-pending) [data-media-model]').getAttribute('data-media-model'), 'wan3.0-video');
  assert.equal(await toggle('wan3.0-video').isChecked(), false);
  assert.equal(await toggle('qwen-image-3.0').isChecked(), true);
  const settings = JSON.parse(await readFile(path.join(directory, 'qoder', 'settings.json'), 'utf8'));
  assert.deepEqual(settings.disabled, ['wan3.0-video']);
  checks.push('disabling wan3.0-video stays in place as a dimmed pending row (#14) and persists to settings.json');
  await page.screenshot({ path: path.join(output, 'qoder-media-disabled-1440.png'), fullPage: true });
  await page.reload();
  await page.getByRole('tab', { name: 'Qoder', exact: true }).click();
  await section.waitFor();
  if (await section.evaluate(element => element.open === false)) await section.locator('summary').first().click();
  await toggle('qwen-image-3.0').waitFor();
  await panel.locator('.proxy-disabled-models > summary').click();
  assert.equal(await toggle('wan3.0-video').isChecked(), false);
  checks.push('after a reload the row regroups into 未启用模型 and stays disabled');
  await toggle('wan3.0-video').check();
  await section.getByText('已保存', { exact: true }).waitFor();
  assert.equal(await toggle('wan3.0-video').isChecked(), true);
  assert.equal(await section.locator('.proxy-model-heading.is-pending').count(), 1);
  await section.locator('[data-refresh-media]').click();
  await section.locator('.proxy-model-heading.is-pending').waitFor({ state: 'detached' });
  assert.equal(await panel.locator('.proxy-disabled-models').count(), 0);
  assert.deepEqual(JSON.parse(await readFile(path.join(directory, 'qoder', 'settings.json'), 'utf8')).disabled, []);
  checks.push('re-enabling stays pending until refresh, which regroups the row');
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  await page.screenshot({ path: path.join(output, 'qoder-media-1440.png'), fullPage: true });
  for (const tab of ['Grok', 'Codex']) { await page.getByRole('tab', { name: tab, exact: true }).click(); assert.equal(await page.locator('#proxy-panel-' + tab.toLowerCase() + ' [data-media-list] .ui-media-model:visible').count(), 0); }
  checks.push('other sources without a login show no Qoder rows');
  assert.deepEqual(errors, []);
  assert.equal(upstream.some(url => /service\/pro/.test(url)), false);
  checks.push('no media upstream request was made');
  console.log(JSON.stringify({ passed: checks.length, checks, errors, output }, null, 2));
} finally { await browser.close(); await server.closeProxy(); await new Promise(resolve => { server.close(resolve); server.closeAllConnections(); }); await rm(directory, { recursive: true, force: true }); }
